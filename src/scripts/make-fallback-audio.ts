// LEA-160: records the four sentences the engine plays when OpenAI cannot speak (see src/fallback-audio.ts).
// Run once by hand: OPENAI_API_KEY=... npx ts-node src/scripts/make-fallback-audio.ts
// It asks OpenAI for speech, converts it to the phone line's format (μ-law 8 kHz) and writes src/fallback-audio-data.ts.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { TelephonyConverter } from "../audio";

// Written to suit both "vykání" and "tykání" and either gender of the assistant.
const SENTENCES = {
  cs: {
    wait: "Chviličku, spojení se na okamžik přerušilo.",
    apology: "Omlouvám se, došlo k technické závadě a nemohu pokračovat. Zavolejte prosím za chvíli znovu. Děkuji a na slyšenou.",
  },
  en: {
    wait: "One moment, the connection was briefly interrupted.",
    apology: "I'm sorry, a technical problem means I can't continue. Please call again in a moment. Thank you, goodbye.",
  },
} as const;

const STYLE = {
  cs: "Mluv přirozenou, plynulou češtinou rodilé mluvčí, klidným a přátelským tónem profesionální recepční.",
  en: "Speak natural, fluent English in a calm, friendly, professional receptionist tone.",
};

async function speak(text: string, language: "cs" | "en"): Promise<string> {
  const res = await fetch("https://api.openai.com/v1/audio/speech", {
    method: "POST",
    headers: { Authorization: `Bearer ${process.env.OPENAI_API_KEY}`, "Content-Type": "application/json" },
    body: JSON.stringify({ model: "gpt-4o-mini-tts", voice: "marin", input: text, instructions: STYLE[language], response_format: "pcm" }),
  });
  if (!res.ok) throw new Error(`speech request failed: ${res.status}`);
  const pcm24 = Buffer.from(await res.arrayBuffer()); // PCM16, 24 kHz, mono
  const converter = new TelephonyConverter();
  return converter.toPhone(pcm24.toString("base64"));
}

async function main(): Promise<void> {
  if (!process.env.OPENAI_API_KEY) throw new Error("OPENAI_API_KEY not set");
  const data: Record<string, Record<string, string>> = { cs: {}, en: {} };
  for (const language of ["cs", "en"] as const) {
    for (const kind of ["wait", "apology"] as const) {
      data[language][kind] = await speak(SENTENCES[language][kind], language);
      console.log(`${language}/${kind}: ${Math.round(Buffer.from(data[language][kind], "base64").length / 8)} ms`);
    }
  }
  const out = `// Generated by src/scripts/make-fallback-audio.ts (see fallback-audio.ts). Do not edit by hand.
export const FALLBACK_CLIPS: Record<"cs" | "en", Record<"wait" | "apology", string>> = ${JSON.stringify(data, null, 2)};
`;
  writeFileSync(join(__dirname, "..", "fallback-audio-data.ts"), out);
}

main().catch((e) => { console.error(e instanceof Error ? e.message : e); process.exit(1); });
